/** Returns the FIC country name for an ISO code, or null if FIC does not know it. */
export function getCountryNameForFIC(isoCode: string): string | null {
  if (!isoCode) return null;
  return FIC_COUNTRY_NAMES[isoCode.toUpperCase()] ?? null;
}
